"""Генератор презентации «Тестирование» для детей 10 лет.

Заменяет пример «Камень–Ножницы–Бумага» на нашу игру «Покорми птенчика»:
- ручное тестирование — запуск настоящей игры и клики руками
- автотесты — демо гоняет тесты автоматически
"""

import os
from pptx import Presentation
from pptx.util import Inches, Pt, Emu
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "Тестирование_для_детей.pptx")

# Палитра
SUNNY = RGBColor(0xFF, 0xBB, 0x33)
CREAM = RGBColor(0xFF, 0xF6, 0xE5)
INK = RGBColor(0x4A, 0x3B, 0x28)
GREEN = RGBColor(0x7B, 0xC6, 0x7E)
CARD = RGBColor(0xFF, 0xFF, 0xFF)
ACCENT = RGBColor(0xF5, 0x7F, 0x17)

FONT = "Comic Sans MS"


def make_presentation():
    prs = Presentation()
    prs.slide_width = Inches(13.333)
    prs.slide_height = Inches(7.5)
    blank = prs.slide_layouts[6]

    def new_slide(bg=CREAM):
        s = prs.slides.add_slide(blank)
        shp = s.shapes.add_shape(1, 0, 0, prs.slide_width, prs.slide_height)
        shp.fill.solid()
        shp.fill.fore_color.rgb = bg
        shp.line.fill.background()
        return s

    def title(slide, text):
        tb = slide.shapes.add_textbox(Inches(0.7), Inches(0.35), prs.slide_width - 1.4, Inches(1.1))
        tf = tb.text_frame
        tf.word_wrap = True
        p = tf.paragraphs[0]
        r = p.add_run(); r.text = text
        r.font.size = Pt(38); r.font.bold = True
        r.font.color.rgb = GREEN; r.font.name = "Comic Sans MS"

    def bullets(slide, items, top=1.7, size=24, gap=0.35, color=INK):
        y = Inches(top)
        for it in items:
            tb = slide.shapes.add_textbox(Inches(1.0), y, prs.slide_width - Inches(2.0), Inches(0.6))
            tf = tb.text_frame; tf.word_wrap = True
            p = tf.paragraphs[0]
            r = p.add_run(); r.text = it
            r.font.size = Pt(size); r.font.color.rgb = color; r.font.name = "Comic Sans MS"
            y += Inches(gap)

    # ---------------- Slide 1: тема ----------------
    s = new_slide(SUNNY)
    tb = s.shapes.add_textbox(Inches(1.5), Inches(2.2), prs.slide_width - 3, Inches(2.4))
    tf = tb.text_frame; tf.word_wrap = True
    p = tf.paragraphs[0]; r = p.add_run(); r.text = "Тестирование и профессия\nавтотестировщика"
    r.font.size = Pt(52); r.font.bold = True; r.font.color.rgb = INK; r.font.name = "Comic Sans MS"
    p.alignment = PP_ALIGN.CENTER
    tb = s.shapes.add_textbox(Inches(2.0), Inches(4.6), prs.slide_width - 4, Inches(1.5))
    p = tb.text_frame.paragraphs[0]; r = p.add_run()
    r.text = "Как находят ошибки в играх — и как это можно автоматизировать"
    r.font.size = Pt(24); r.font.color.rgb = INK; r.font.name = "Comic Sans MS"
    p.alignment = PP_ALIGN.CENTER

    # ---------------- Слайд 2: что такое тестирование ----------------
    s = new_slide()
    title(s, "Что такое тестирование")
    bullets(s, [
        "Тестирование — это проверка, что всё работает правильно.",
        "Мы проверяем: игры, приложения, сайты, устройства.",
        "Не только код — вообще всё, чем пользуются люди.",
    ])

    # ---------------- Слайд 3: зачем ----------------
    s = new_slide()
    title(s, "Зачем оно нужно")
    bullets(s, [
        "Если есть ошибка — игра может «ломаться» или «подвисать».",
        "Тестирование помогает:",
        "  • находить ошибки раньше,",
        "  • делать продукт надёжнее,",
        "  • выпускать обновления спокойнее.",
    ])

    # ---------------- Слайд 4: баг ----------------
    s = new_slide()
    title(s, "Что такое баг")
    bullets(s, [
        "Баг — когда программа ведёт себя не так, как задумано.",
        "Примеры багов:",
        "  • кнопка не нажимается,",
        "  • вместо результата — ошибка,",
        "  • можно «сломать» игру необычным ходом.",
        "Баги бывают у всех — важно уметь их ловить.",
    ])

    # ---------------- Слайд 5: тестировщик ----------------
    s = new_slide()
    title(s, "Кто такой тестировщик")
    bullets(s, [
        "Тестировщик — человек, который:",
        "  • проверяет продукт разными способами,",
        "  • ищет ошибки,",
        "  • описывает их так, чтобы разработчик быстро исправил.",
        "Тестировщик — как «детектив качества».",
    ])

    # ---------------- Слайд 6: как тестируют вручную ----------------
    s = new_slide()
    title(s, "Как тестируют вручную")
    bullets(s, [
        "Ручное тестирование — когда проверяет человек.",
        "1) придумать проверки (чек-лист)",
        "2) выполнить шаги",
        "3) сравнить: «что ожидали» и «что получилось»",
        "4) если ошибка — записать, как её повторить",
    ])

    # ---------------- Слайд 7: практика №1, ручная, наша игра ----------------
    s = new_slide()
    title(s, "Практика. Тестируем игру «Покорми птенчика»")
    bullets(s, [
        "Сейчас мы запустим настоящую игру на компьютере!",
        "Задание: покликай по клеткам и проверь:",
        "  • птенчик ходит только на соседние клетки,",
        "  • нельзя ходить по диагонали и перепрыгивать,",
        "  • если нажать не ту клетку — птенчик не должен уходить.",
        "Попробуй довести птенчика до зерна и выиграть.",
    ])

    # ---------------- Слайд 8: пример чек-листа ----------------
    s = new_slide()
    title(s, "Пример чек-листа для нашей игры")
    bullets(s, [
        "Жёлтый кружок = птенчик, коричневое зёрнышко = зерно.",
        "Ход вправо → птенчик перемещается на клетку вправо ✔",
        "Ход через 1 клетку → появляется окно «Ходить можно только...» ✔",
        "Ход за границу поля → ход не выполняется ✔",
        "Дойти до зерна → «Птенчик поел и доволен!» ✔",
        "Новая игра → зерно на новом месте, птенчик в центре ✔",
    ])

    # ---------------- Слайд 9: автотесты ----------------
    s = new_slide()
    title(s, "Что такое автотесты")
    bullets(s, [
        "Автотесты — когда программа сама проверяет программу.",
        "Зачем:",
        "  • не повторять одно и то же руками каждый раз,",
        "  • сразу понять: «ничего не сломалось?»",
        "Особенно полезно, когда продукт часто обновляют.",
    ])

    # ---------------- Слайд 10: автотестировщик ----------------
    s = new_slide()
    title(s, "Кто такой автотестировщик")
    bullets(s, [
        "Автотестировщик — тестировщик, который умеет:",
        "  • писать простые проверки кодом,",
        "  • запускать их автоматически,",
        "  • быстро находить, что сломалось.",
        "Формула: автотестировщик = тестирование + немного программирования",
    ])

    # ---------------- Слайд 11: практика №2 ----------------
    s = new_slide()
    title(s, "Практика №2: мы уже написали тесты к игре!")
    bullets(s, [
        "Вместе с игрой мы написали автотесты.",
        "Они проверяют правила хода, победу и «Новую игру».",
        "Сейчас запустим ДЕМО — и тесты сами погонят игру.",
        "Смотри: птенчик ходит сам, без нашей помощи!",
    ])

    # ---------------- Слайд 12: как выглядит тест ----------------
    s = new_slide()
    title(s, "Как выглядит простой тест")
    bullets(s, [
        "Это проверка одной задачки:",
        "  • верно ли, что из клетки (2,2) можно пойти вправо?",
        "  • верно ли, что птенчик стартует в центре?",
        "Тест — это просто «вопрос + ожидаемый ответ».",
    ])

    # ---------------- Слайд 13: запуск ----------------
    s = new_slide()
    title(s, "Итак, запускаем автотесты")
    bullets(s, [
        "Команда: python3 -m unittest",
        "Тесты бегают сами, без кликов,",
        "и печатают: сколько проверок прошло.",
        "Это и есть автоматическое тестирование.",
    ])

    # ---------------- Слайд 14: баг нашли ----------------
    s = new_slide()
    title(s, "Вау-момент: «сломай игру и поймай баг»")
    bullets(s, [
        "Что если в коде «забыть» правило?",
        "Например, разрешить ходить по диагонали.",
        "Снова запускаем тесты — и они сразу находят проблему!",
        "Вот так автотесты ловят ошибки сами.",
    ])

    # ---------------- Слайд 15 ----------------
    s = new_slide()
    title(s, "Почему профессия востребована")
    bullets(s, [
        "Игр и приложений много, они часто обновляются,",
        "и всем важно качество.",
        "Тестировщик помогает:",
        "  • выпускать обновления быстрее,",
        "  • находить проблемы раньше пользователей,",
        "  • делать продукт надёжнее.",
    ])

    # ---------------- Слайд 16 ----------------
    s = new_slide()
    title(s, "Что можно делать уже сейчас")
    bullets(s, [
        "Тестировать любимые игры: «а что будет, если...?»",
        "Учить базовый Python: строки, if, функции.",
        "Делать маленькие проекты: «игра + 5–10 тестов».",
    ])

    # ---------------- Слайд 17 ----------------
    s = new_slide(SUNNY)
    title(s, "Вопросы")
    tb = s.shapes.add_textbox(Inches(1.2), Inches(2.2), prs.slide_width - Inches(2.4), Inches(3))
    tf = tb.text_frame; tf.word_wrap = True
    p = tf.paragraphs[0]; r = p.add_run()
    r.text = "Что вам больше понравилось: кликать по игре (как детектив) или писать автотесты (как инженер)?"
    r.font.size = Pt(30); r.font.color.rgb = INK; r.font.name = "Comic Sans MS"
    p.alignment = PP_ALIGN.CENTER

    prs.save(OUT)
    print("Сохранено:", OUT)


if __name__ == "__main__":
    make_presentation()